static int prepare_keys(void)
{
    unsigned int card;
    memset(keys, 0, sizeof(keys));
    for (card = 0; card < 2; card++) {
        unsigned int id, i;
        for (id = 0; id < 4; id++) {
            struct { uint32_t before[4]; char text[32]; uint32_t after[4]; } guarded;
            int status;
            memset(&guarded, 0xa5, sizeof(guarded));
            memset(guarded.text, 0, sizeof(guarded.text));
            switch (id) {
            case BASE: status = WlanCardIndex2BaseInstId(card, guarded.text); break;
            case CFG: status = WlanIndex2InstId(card, 0, guarded.text); break;
            case SSID: status = WlanIndex2SSIDInstId(card, 0, guarded.text); break;
            default: status = WlanIndex2PSKInstId(card, 0, guarded.text); break;
            }
            if (status || !memchr(guarded.text, 0, 32))
                return -1;
            for (i = 0; i < 4; i++)
                if (guarded.before[i] != GUARD || guarded.after[i] != GUARD)
                    return -1;
            memcpy(keys[id][card], guarded.text, 32);
        }
    }
    for (card = 0; card < 4; card++)
        if (!keys[card][0][0] || !keys[card][1][0] ||
            !memchr(keys[card][0], 0, 32) || !memchr(keys[card][1], 0, 32) ||
            !strcmp(keys[card][0], keys[card][1]))
            return -1;
    return 0;
}

static size_t offset(const struct profile *p, unsigned int index)
{
    size_t pos = 8;
    unsigned int i;
    if (index > p->count)
        return 0;
    for (i = 0; i < index; i++) {
        unsigned int n = dbGetPmTypeValLen(p->fields[i].type);
        if (!n || pos > p->bytes || n > p->bytes - pos)
            return 0;
        pos += n;
    }
    return pos;
}

struct query { uint32_t before[4], data[MAX_VIEW / 4], after[4]; };
static void init(struct query *q, unsigned int id)
{
    memset(q, 0xa5, sizeof(*q));
    memset(q->data, 0, sizeof(q->data));
    q->data[0] = profiles[id].bytes;
    q->data[1] = MAGIC;
}

static int validate(const struct query *q, unsigned int id)
{
    const struct profile *p = &profiles[id];
    unsigned int i;
    if (q->data[0] != p->bytes || q->data[1] != MAGIC || offset(p, p->count) != p->bytes)
        return -1;
    for (i = 0; i < 4; i++)
        if (q->before[i] != GUARD || q->after[i] != GUARD)
            return -1;
    for (i = p->bytes / 4; i < ARRAY_SIZE(q->data); i++)
        if (q->data[i])
            return -1;
    for (i = 0; i < p->count; i++) {
        const uint8_t *record = (const uint8_t *)q->data + offset(p, i);
        uint16_t type;
        uint32_t status;
        memcpy(&type, record, 2);
        memcpy(&status, record + 24, 4);
        if (type != p->fields[i].type || status)
            return -1;
    }
    return 0;
}

static int field_index(unsigned int id, const char *name)
{
    unsigned int i;
    for (i = 0; i < profiles[id].count; i++)
        if (!strcmp(name, profiles[id].fields[i].name))
            return i;
    return -1;
}

static const uint8_t *value(const struct query *q, unsigned int id, const char *name)
{
    int index = field_index(id, name);
    return index < 0 ? NULL : (const uint8_t *)q->data + offset(&profiles[id], index) + 28;
}

static int text_equals(const struct query *q, unsigned int id, const char *field, const char *wanted)
{
    const uint8_t *v = value(q, id, field);
    int index = field_index(id, field);
    size_t n = strlen(wanted);
    unsigned int cap;
    if (!v || index < 0 || profiles[id].fields[index].type >= 12)
        return 0;
    cap = dbGetPrmValLen(profiles[id].fields[index].type) - 4;
    /* Native strings start directly at +28; the pointer-sized reserve is
     * padding, not a length prefix or an external RPC pointer.
     */
    return n < cap && !memcmp(v, wanted, n) && v[n] == 0;
}

static int set_text(struct query *q, unsigned int id, const char *name, const char *text)
{
    const struct profile *p = &profiles[id];
    int index = field_index(id, name);
    uint8_t *r;
    uint32_t n;
    uint16_t type, mask = 1;
    unsigned int cap;
    if (!text || q->data[0] != p->bytes || q->data[1] != MAGIC || index < 0 ||
            p->fields[index].primary_key || p->fields[index].type >= 12)
        return -1;
    type = p->fields[index].type;
    cap = dbGetPrmValLen(type);
    n = strlen(text);
    if (cap <= 4 || n >= cap - 4)
        return -1;
    r = (uint8_t *)q->data + offset(p, index);
    memset(r, 0, dbGetPmTypeValLen(type));
    memcpy(r, &type, 2);
    memcpy(r + 2, &mask, 2);
    memcpy(r + 28, text, n);
    return 0;
}

static int create(unsigned int id, void **created)
{
    const struct profile *p = &profiles[id];
    uint32_t descriptor[41] = { (uint32_t)(uintptr_t)p->name, 0, p->rows, p->saved };
    uint32_t *table;
    if (offset(p, p->count) != p->bytes)
        return -1;
    table = dbCreateTbl(descriptor);
    /* Test-only common view. Original core views may have CSP callbacks;
     * we do NOT claim their registration/default/service semantics are solved.
     */
    if (!table || dbCreateDomainNew(table, p->fields, (p->count + 1) * sizeof(*p->fields)) ||
            table[18] != p->count || dbMgrCommViewAddItem(p->name, p->name, "", p->bytes,
                                                       id == DEV ? 0 : 1024, NULL,
                                                       id == DEV ? 12 : 63, p->name, "", ""))
        return -1;
    *created = table;
    return 0;
}

static int create_tables(const char *manufacturer, const char *model_name)
{
    void *tables[5];
    unsigned int id, row;
    if (prepare_keys())
        return -1;
    for (id = 0; id < ARRAY_SIZE(profiles); id++) {
        if (create(id, &tables[id]))
            return -1;
        for (row = 0; row < (id == DEV ? 1U : 2U); row++) {
            if (!dbAddRow(tables[id]) || (id != DEV &&
                    dbSetValCommByRowNo(tables[id], row, "ViewName", keys[id][row])))
                return -1;
        }
    }
    /* Preserve the source's field-level flags without acquiring its defaults. */
    if (dbSetDmFlag("WLANCfg", "ESSID", 2) || dbSetDmFlag("WLANCfg", "WPAEAPSecret", 1) ||
        dbSetDmFlag("WLANPSK", "PreSharedKey", 1) || dbSetDmFlag("WLANPSK", "KeyPassphrase", 1))
        return -1;
    for (row = 0; row < 2; row++) {
        if (dbSetValCommByRowNo(tables[BASE], row, "CardIsIn", "1") ||
            dbSetValCommByRowNo(tables[BASE], row, "RadioStatus", "1") ||
            /* The agent applies the BeaconInterval it is sent. The public-zero registry
             * default would push 0; a ZTE radio ships with 100 ms (what a real child has). */
            dbSetValCommByRowNo(tables[BASE], row, "BeaconInterval", "100") ||
            dbSetValCommByRowNo(tables[BASE], row, "Channel", row ? "36" : "1") ||
            dbSetValCommByRowNo(tables[CFG], row, "Enable", "1") ||
            dbSetValCommByRowNo(tables[CFG], row, "InstExist", "1") ||
            /* A real fronthaul AP, not a teardown target: acdGetWLANCFG marks a band
             * for tear-down (Multi-AP ext subelement 0x10) only when every BSS slot's
             * access attribute is zero; MapAccessAttr 0x20 = fronthaul (what the real
             * child advertises) both prevents that and tells the agent to bring the
             * BSS up. BeaconType 3 marks it as a genuine WPA/WPA2 AP. */
            dbSetValCommByRowNo(tables[CFG], row, "MapAccessAttr", "32") ||
            dbSetValCommByRowNo(tables[CFG], row, "BeaconType", "3") ||
            /* The agent applies the per-BSS ACLPolicy we report (SSID vendor message).
             * A real ZTE child ships every fronthaul BSS with 1 (driver AccessPolicy 2,
             * an empty block list) - reporting the DB default 0 silently rewrote it. */
            dbSetValCommByRowNo(tables[CFG], row, "ACLPolicy", "1") ||
            dbSetValCommByRowNo(tables[CFG], row, "ESSID", row ? "zte-shim-lab-5g" : "zte-shim-lab-2g") ||
            dbSetValCommByRowNo(tables[PSK], row, "WLANViewName", keys[CFG][row]) ||
            dbSetValCommByRowNo(tables[PSK], row, "KeyPassphrase", "zte-shim-lab-not-a-live-key") ||
            dbSetValCommByRowNo(tables[SSID], row, "Name", row ? "lab-radio-b" : "lab-radio-a"))
            return -1;
    }
    /* SerialNumber/AliasName stay the obvious PUBLIC placeholders everywhere, even for
     * the real-identity caller: the device-identity-ext gate (verified by disassembly,
     * not guessed) only strcasecmp's the ModelName slot, never these two. */
    if (dbSetValCommByRowNo(tables[DEV], 0, "ManuFacturer", manufacturer) ||
        dbSetValCommByRowNo(tables[DEV], 0, "ModelName", model_name) ||
        dbSetValCommByRowNo(tables[DEV], 0, "SerialNumber", "PUBLIC-NOT-DEVICE-SERIAL") ||
        dbSetValCommByRowNo(tables[DEV], 0, "AliasName", "zte-shim-public-lab"))
        return -1;
    return 0;
}

/* BeaconType values the factory UI offers (FEATURE_MAP section 12): 0 open, 3 WPA2, 6 WPA + WPA2, 10 WPA3, 12 WPA3 + WPA2. */
int wlan_profiles_beacon_type_ok(unsigned int beacon_type)
{
    return beacon_type == 0 || beacon_type == 3 || beacon_type == 6 || beacon_type == 10 || beacon_type == 12;
}

/* WLANCfg row number of every BSS slot (slot 0 of radio r is row r). */
static unsigned int cfg_row_of[2][4] = { {0, 0, 0, 0}, {1, 0, 0, 0} };

int wlan_profiles_add_extra_bss(unsigned int radio, unsigned int slot, int enabled,
                                const char *ssid, const char *key)
{
    static unsigned int next_row = 2;
    extern void *dbFindTbl(const char *);
    char cfg_key[32], psk_key[32];
    void *cfg = dbFindTbl("WLANCfg"), *psk = dbFindTbl("WLANPSK");
    unsigned int row = next_row;
    if (radio > 1 || slot < 1 || slot > 3 || !cfg || !psk || !ssid || !key || !*ssid ||
        strlen(key) < 8 || WlanIndex2InstId(radio, slot, cfg_key) ||
        WlanIndex2PSKInstId(radio, slot, psk_key))
        return -1;
    if (!dbAddRow(cfg) || !dbAddRow(psk) ||
        dbSetValCommByRowNo(cfg, row, "ViewName", cfg_key) ||
        dbSetValCommByRowNo(cfg, row, "Enable", enabled ? "1" : "0") ||
        dbSetValCommByRowNo(cfg, row, "InstExist", "1") ||
        /* Factory baseline per slot: 32 for the fronthaul slots, 64 for slot 3 (the hidden backhaul BSS),
         * VapIsolationEnable only on the guest slot 1 (the slot message fields 0f / 1e). */
        dbSetValCommByRowNo(cfg, row, "MapAccessAttr", slot == 3 ? "64" : "32") ||
        dbSetValCommByRowNo(cfg, row, "VapIsolationEnable", slot == 1 ? "1" : "0") ||
        dbSetValCommByRowNo(cfg, row, "BeaconType", "3") ||
        dbSetValCommByRowNo(cfg, row, "11iAuthMode", "0") ||
        dbSetValCommByRowNo(cfg, row, "11iEncryptType", "1") ||
        dbSetValCommByRowNo(cfg, row, "GuestSsid", slot == 1 ? "1" : "0") ||
        /* Same mirror of the child's own default as the primary slots (1); slot 3 is
         * the hidden backhaul BSS on a real child, which ships 0. */
        dbSetValCommByRowNo(cfg, row, "ACLPolicy", slot == 3 ? "0" : "1") ||
        dbSetValCommByRowNo(cfg, row, "ESSID", ssid) ||
        dbSetValCommByRowNo(psk, row, "ViewName", psk_key) ||
        dbSetValCommByRowNo(psk, row, "WLANViewName", cfg_key) ||
        dbSetValCommByRowNo(psk, row, "KeyPassphrase", key))
        return -1;
    cfg_row_of[radio][slot] = row;
    next_row++;
    return 0;
}

int wlan_profiles_set_extra_bss_style(unsigned int radio, unsigned int slot, int hidden, unsigned int beacon_type)
{
    extern void *dbFindTbl(const char *);
    void *cfg = dbFindTbl("WLANCfg");
    char value[8];
    if (radio > 1 || slot < 1 || slot > 3 || !cfg || !cfg_row_of[radio][slot] ||
        !wlan_profiles_beacon_type_ok(beacon_type))
        return -1;
    snprintf(value, sizeof(value), "%u", beacon_type);
    return dbSetValCommByRowNo(cfg, cfg_row_of[radio][slot], "ESSIDHideEnable", hidden ? "1" : "0") ||
           dbSetValCommByRowNo(cfg, cfg_row_of[radio][slot], "BeaconType", value) ? -1 : 0;
}

extern void *dbFindTbl(const char *);
extern int ShmPoolLock(unsigned int);
extern int ShmPoolUnlock(void);

static unsigned int bss_row_of[2][4]; /* P1905AcdBssCfg row of every extra slot (0 = none) */

void wlan_profiles_note_bss_row(unsigned int radio, unsigned int slot, unsigned int row)
{
    if (radio < 2 && slot >= 1 && slot < 4)
        bss_row_of[radio][slot] = row;
}

/* Rows of an extra slot exist (created at start-up or by an earlier live add). */
int wlan_profiles_slot_known(unsigned int radio, unsigned int slot)
{
    return radio < 2 && slot >= 1 && slot < 4 && cfg_row_of[radio][slot] && bss_row_of[radio][slot];
}

/* Make an extra slot visible to / invisible from the daemon's ACD module (0 = ok). The ACD builds its per-BSS list from
 * P1905AcdBssCfg only when it starts: a slot takes part in the M2 and the slot replies while its row's CustomTag has
 * bit 2 (68 = bits 2 and 6, enable bit not overridden, REPLAY_RESULTS section 14), and not at all with CustomTag 0.
 * A removed slot also reads as "not instantiated" (WLANCfg.InstExist 0, disabled), the same as one that was never
 * configured. The rows stay, so a later add reuses them. The caller restarts the daemon. */
int wlan_profiles_set_slot_present(unsigned int radio, unsigned int slot, int present)
{
    void *cfg = dbFindTbl("WLANCfg"), *bss = dbFindTbl("P1905AcdBssCfg");
    int status;
    if (!wlan_profiles_slot_known(radio, slot) || !cfg || !bss || ShmPoolLock(1000))
        return -1;
    status = dbSetValCommByRowNo(cfg, cfg_row_of[radio][slot], "InstExist", present ? "1" : "0") ||
             (!present && dbSetValCommByRowNo(cfg, cfg_row_of[radio][slot], "Enable", "0")) ||
             dbSetValCommByRowNo(bss, bss_row_of[radio][slot], "CustomTag", present ? "68" : "0") ||
             (!present && dbSetValCommByRowNo(bss, bss_row_of[radio][slot], "Enable", "0"));
    (void)ShmPoolUnlock();
    return status ? -1 : 0;
}

int wlan_profiles_set_main_style(unsigned int radio, int hidden, unsigned int beacon_type)
{
    void *cfg = dbFindTbl("WLANCfg");
    char value[8];
    int status;
    if (radio > 1 || !cfg || !wlan_profiles_beacon_type_ok(beacon_type))
        return -1;
    snprintf(value, sizeof(value), "%u", beacon_type);
    if (ShmPoolLock(1000))
        return -1;
    status = dbSetValCommByRowNo(cfg, cfg_row_of[radio][0], "ESSIDHideEnable", hidden ? "1" : "0") ||
             dbSetValCommByRowNo(cfg, cfg_row_of[radio][0], "BeaconType", value);
    (void)ShmPoolUnlock();
    return status ? -1 : 0;
}

int wlan_profiles_set_acl_policy(unsigned int radio, unsigned int slot, int policy, int hot)
{
    void *cfg = dbFindTbl("WLANCfg");
    char value[4];
    int status;
    if (radio > 1 || slot > 3 || policy < 0 || policy > 2 || !cfg || (slot && !cfg_row_of[radio][slot]))
        return -1;
    snprintf(value, sizeof(value), "%d", policy);
    if (hot && ShmPoolLock(1000))
        return -1;
    status = dbSetValCommByRowNo(cfg, cfg_row_of[radio][slot], "ACLPolicy", value);
    if (hot)
        (void)ShmPoolUnlock();
    return status ? -1 : 0;
}

int wlan_profiles_acl_apply(const struct wlan_acl_rule *rules, unsigned int count, int hot)
{
    struct { char name[32], interface[32], mac[18]; } row[WLAN_ACL_ROWS];
    void *table = dbFindTbl("AclCfg");
    unsigned int i, n = 0, radio;
    int status = 0;
    if (!table || count > WLAN_ACL_RULES || (count && !rules))
        return -1;
    memset(row, 0, sizeof(row));
    for (i = 0; i < WLAN_ACL_ROWS; i++)
        snprintf(row[i].mac, sizeof(row[i].mac), "00:00:00:00:00:00");
    for (i = 0; i < count; i++) {
        for (radio = 0; radio < 2; radio++) {
            if (rules[i].radio != 2 && rules[i].radio != (int)radio)
                continue;
            if (n >= WLAN_ACL_ROWS || rules[i].bss < 0 || rules[i].bss > 3 ||
                WlanIndex2InstId(radio, (unsigned int)rules[i].bss, row[n].interface) ||
                snprintf(row[n].name, sizeof(row[n].name), "%s%s", rules[i].name, radio ? "_5G" : "") >= (int)sizeof(row[n].name))
                return -1;
            snprintf(row[n].mac, sizeof(row[n].mac), "%s", rules[i].mac);
            n++;
        }
    }
    if (hot && ShmPoolLock(1000))
        return -1;
    for (i = 0; i < WLAN_ACL_ROWS && !status; i++) {
        char key[16];
        snprintf(key, sizeof(key), "ACLCFG%u", i + 1);
        status = dbSetValCommByRowNo(table, i, "ViewName", key) ||
                 dbSetValCommByRowNo(table, i, "Name", row[i].name) ||
                 dbSetValCommByRowNo(table, i, "Interface", row[i].interface) ||
                 dbSetValCommByRowNo(table, i, "MACAddress", row[i].mac) ||
                 dbSetValCommByRowNo(table, i, "ACLCfgPolicy", "0");
    }
    if (hot)
        (void)ShmPoolUnlock();
    return status ? -1 : 0;
}

