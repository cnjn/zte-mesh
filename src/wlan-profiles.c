static int restore_query(struct query *out, const struct query *snapshot, unsigned int id)
{
    static const char *cfg_names[] = { "ESSID", "Enable", "BeaconType", "11iEncryptType", "11iAuthMode" };
    static const char *psk_names[] = { "PreSharedKey", "KeyPassphrase" };
    const char *const *names = id == CFG ? cfg_names : psk_names;
    unsigned int count = id == CFG ? ARRAY_SIZE(cfg_names) : ARRAY_SIZE(psk_names), j;
    uint16_t mask = 1;
    init(out, id);
    for (j = 0; j < count; j++) {
        int i = field_index(id, names[j]);
        size_t off;
        if (i < 0)
            return -1;
        off = offset(&profiles[id], i);
        memcpy((uint8_t *)out->data + off, (const uint8_t *)snapshot->data + off,
               dbGetPmTypeValLen(profiles[id].fields[i].type));
        memcpy((uint8_t *)out->data + off + 2, &mask, 2);
    }
    return 0;
}

static int unselected_unchanged(const struct query *now, const struct query *before, unsigned int id)
{
    unsigned int i;
    for (i = 0; i < profiles[id].count; i++) {
        const char *n = profiles[id].fields[i].name;
        size_t off = offset(&profiles[id], i);
        int selected = id == CFG ? (!strcmp(n, "ESSID") || !strcmp(n, "Enable") ||
            !strcmp(n, "BeaconType") || !strcmp(n, "11iEncryptType") || !strcmp(n, "11iAuthMode")) :
            (!strcmp(n, "PreSharedKey") || !strcmp(n, "KeyPassphrase"));
        if (!selected && memcmp((const uint8_t *)now->data + off, (const uint8_t *)before->data + off,
                               dbGetPmTypeValLen(profiles[id].fields[i].type)))
            return -1;
    }
    return 0;
}

int wlan_profiles_bridge_apply(const struct mb_profile *p, int test_failure, struct mb_result *result)
{
    struct query old_cfg, old_psk, other_cfg, other_psk, update, check;
    unsigned int target, other;
    int status = MB_DB_ERROR, changed = 0;
    if (!result)
        return MB_BAD_CONFIG;
    memset(result, 0, sizeof(*result));
    result->request_id = p ? p->request_id : 0;
    result->flags = MB_REJECTED;
    if (mb_validate(p) || (test_failure != 0 && test_failure != 1)) {
        result->status = MB_BAD_CONFIG;
        return MB_BAD_CONFIG;
    }
    target = p->radio; other = 1U - target;
    if (prepare_keys() || get(&old_cfg, CFG, target) || get(&old_psk, PSK, target) ||
        get(&other_cfg, CFG, other) || get(&other_psk, PSK, other))
        goto done;
    /* Only the hash-pinned PUBLIC enum tuple 11i/PSK/AES is supported.
     * No arbitrary numeric enum, key, view, column or driver opcode crosses wire.
     */
    init(&update, CFG);
    if (set_text(&update, CFG, "ESSID", p->ssid) || set_scalar(&update, CFG, "Enable", p->enabled) ||
        set_scalar(&update, CFG, "BeaconType", MB_VENDOR_BEACON_WPA2) ||
        set_scalar(&update, CFG, "11iEncryptType", MB_VENDOR_CIPHER_AES) ||
        set_scalar(&update, CFG, "11iAuthMode", MB_VENDOR_AUTH_PSK))
        goto done;
    changed = 1; /* A failing SET may still have partially written fields. */
    if (dbAPISetView("WLANCfg", keys[CFG][target], update.data))
        goto rollback;
    init(&update, PSK);
    if (set_text(&update, PSK, "PreSharedKey", "") || set_text(&update, PSK, "KeyPassphrase", p->key))
        goto rollback;
    if (test_failure)
        update.data[0]--; /* Fixed test mode: provoke real factory length error. */
    {
        int set_status = dbAPISetView("WLANPSK", keys[PSK][target], update.data);
        if (test_failure && set_status != -15) {
            status = MB_VERIFY_ERROR;
            goto rollback;
        }
        if (set_status)
            goto rollback;
    }
    status = MB_VERIFY_ERROR;
    if (get(&check, CFG, target) || !text_equals(&check, CFG, "ESSID", p->ssid) ||
        scalar(&check, CFG, "Enable") != p->enabled ||
        scalar(&check, CFG, "BeaconType") != MB_VENDOR_BEACON_WPA2 ||
        scalar(&check, CFG, "11iEncryptType") != MB_VENDOR_CIPHER_AES ||
        scalar(&check, CFG, "11iAuthMode") != MB_VENDOR_AUTH_PSK ||
        unselected_unchanged(&check, &old_cfg, CFG) || get(&check, PSK, target) || !text_equals(&check, PSK, "KeyPassphrase", p->key) ||
        !text_equals(&check, PSK, "PreSharedKey", "") || unselected_unchanged(&check, &old_psk, PSK) ||
        get(&check, CFG, other) || memcmp(check.data, other_cfg.data, profiles[CFG].bytes) ||
        get(&check, PSK, other) || memcmp(check.data, other_psk.data, profiles[PSK].bytes))
        goto rollback;
    result->generation = 1;
    result->flags = MB_READBACK | MB_OTHER_ROW;
    status = MB_OK;
    goto done;
rollback:
    /* Two factory SETs are NOT atomic. Best-effort restore is explicitly
     * verified; rollback failure stays visible and must stop the caller.
     */
    if (restore_query(&update, &old_cfg, CFG) || dbAPISetView("WLANCfg", keys[CFG][target], update.data) ||
        restore_query(&update, &old_psk, PSK) || dbAPISetView("WLANPSK", keys[PSK][target], update.data) ||
        get(&check, CFG, target) || memcmp(check.data, old_cfg.data, profiles[CFG].bytes) ||
        get(&check, PSK, target) || memcmp(check.data, old_psk.data, profiles[PSK].bytes) ||
        get(&check, CFG, other) || memcmp(check.data, other_cfg.data, profiles[CFG].bytes) ||
        get(&check, PSK, other) || memcmp(check.data, other_psk.data, profiles[PSK].bytes)) {
        status = MB_ROLLBACK_ERROR;
        result->flags = 0;
    } else {
        result->flags = MB_ROLLED_BACK;
    }
done:
    if (status && changed && result->flags == MB_REJECTED) {
        status = MB_ROLLBACK_ERROR;
        result->flags = 0;
    }
    result->status = status;
    mb_wipe(&old_cfg, sizeof(old_cfg)); mb_wipe(&old_psk, sizeof(old_psk));
    mb_wipe(&other_cfg, sizeof(other_cfg)); mb_wipe(&other_psk, sizeof(other_psk));
    mb_wipe(&update, sizeof(update)); mb_wipe(&check, sizeof(check));
    return status;
}
